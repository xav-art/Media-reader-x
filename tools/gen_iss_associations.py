"""Generate the Inno Setup [Registry] section for per-user "Open with" support.

Reads mediareaderx.formats.ASSOCIATION_EXTS so the installer never drifts from
what the app can open. Everything is written under HKA (= HKCU for a per-user
install): no admin rights, and Windows' own defaults are never overwritten.
The user picks Media Reader x via "Open with" or Settings > Default apps.

Usage: python tools/gen_iss_associations.py packaging/associations.iss
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from mediareaderx.formats import ASSOCIATION_EXTS  # noqa: E402

PROGID = "MediaReaderX.File"
CAPS = r"Software\xav-art\MediaReaderX\Capabilities"


def build() -> str:
    t = "Tasks: associate"
    lines = [
        "; GENERATED by tools/gen_iss_associations.py - do not edit by hand.",
        "[Registry]",
        rf'Root: HKA; Subkey: "Software\Classes\{PROGID}"; ValueType: string; ValueName: ""; '
        rf'ValueData: "Media file"; Flags: uninsdeletekey; {t}',
        rf'Root: HKA; Subkey: "Software\Classes\{PROGID}\DefaultIcon"; ValueType: string; ValueName: ""; '
        rf'ValueData: "{{app}}\MediaReaderX.exe,0"; {t}',
        rf'Root: HKA; Subkey: "Software\Classes\{PROGID}\shell\open\command"; ValueType: string; ValueName: ""; '
        rf'ValueData: """{{app}}\MediaReaderX.exe"" ""%1"""; {t}',
        r'Root: HKA; Subkey: "Software\Classes\Applications\MediaReaderX.exe"; ValueType: string; '
        rf'ValueName: "FriendlyAppName"; ValueData: "Media Reader x"; Flags: uninsdeletekey; {t}',
        r'Root: HKA; Subkey: "Software\Classes\Applications\MediaReaderX.exe\shell\open\command"; '
        rf'ValueType: string; ValueName: ""; ValueData: """{{app}}\MediaReaderX.exe"" ""%1"""; {t}',
        rf'Root: HKA; Subkey: "Software\xav-art\MediaReaderX"; Flags: uninsdeletekey; {t}',
        rf'Root: HKA; Subkey: "{CAPS}"; ValueType: string; ValueName: "ApplicationName"; '
        rf'ValueData: "Media Reader x"; {t}',
        rf'Root: HKA; Subkey: "{CAPS}"; ValueType: string; ValueName: "ApplicationDescription"; '
        rf'ValueData: "Offline viewer for HEIC, AVIF, JPEG XL, RAW and modern video"; {t}',
        r'Root: HKA; Subkey: "Software\RegisteredApplications"; ValueType: string; '
        rf'ValueName: "Media Reader x"; ValueData: "{CAPS}"; Flags: uninsdeletevalue; {t}',
    ]
    for ext in sorted(ASSOCIATION_EXTS):
        lines += [
            rf'Root: HKA; Subkey: "Software\Classes\{ext}\OpenWithProgids"; ValueType: string; '
            rf'ValueName: "{PROGID}"; ValueData: ""; Flags: uninsdeletevalue; {t}',
            r'Root: HKA; Subkey: "Software\Classes\Applications\MediaReaderX.exe\SupportedTypes"; '
            rf'ValueType: string; ValueName: "{ext}"; ValueData: ""; {t}',
            rf'Root: HKA; Subkey: "{CAPS}\FileAssociations"; ValueType: string; ValueName: "{ext}"; '
            rf'ValueData: "{PROGID}"; {t}',
        ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    out = Path(sys.argv[1] if len(sys.argv) > 1 else "packaging/associations.iss")
    out.write_text(build(), encoding="utf-8")
    print(f"{len(ASSOCIATION_EXTS)} extensions written to {out}")
